-- RESTRO PRO - Supabase migration 0029
--   1. products.sort_order        - the order of menu items. Menu page -> "Rearrange" saves it; POS shows items in it
--                                   (within their category). IDENTITY column, like migration 0016: a product created later
--                                   automatically goes to the end of the list. Existing products are numbered once,
--                                   per category, by name (their previous order).
--   2. expense_categories.sort_order - the order of expense categories (Users & Permissions page); the Expenses page
--                                   category list follows it. Same identity approach.
--   3. inventory_items.deleted_at - "Remove" on the Inventory page hides an item instead of deleting it (so history,
--                                   purchases and old productions keep working), like products.deleted_at (0018).
-- Safe to run twice.
-- =====================================================================
alter table public.inventory_items add column if not exists deleted_at timestamptz;

do $$
begin
  if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'products' and column_name = 'sort_order') then
    alter table public.products add column sort_order bigint generated by default as identity;
    update public.products p set sort_order = r.rn
      from (select id, row_number() over (partition by restaurant_id, category_id order by name) as rn from public.products) r
      where r.id = p.id;
  end if;

  if not exists (select 1 from information_schema.columns where table_schema = 'public' and table_name = 'expense_categories' and column_name = 'sort_order') then
    alter table public.expense_categories add column sort_order bigint generated by default as identity;
    update public.expense_categories c set sort_order = r.rn
      from (select id, row_number() over (partition by restaurant_id order by name) as rn from public.expense_categories) r
      where r.id = c.id;
  end if;
end $$;

notify pgrst, 'reload schema';
